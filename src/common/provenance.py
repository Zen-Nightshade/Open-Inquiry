from __future__ import annotations

from enum import Enum
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field


class ProvenanceOrigin(str, Enum):
    """Classification of output origin."""

    MODEL = "model"                                # Generated by LLM
    DETERMINISTIC_RULE = "deterministic_rule"      # Deterministic logic or calculation
    HEURISTIC_FALLBACK = "heuristic_fallback"      # Fallback approximation used when primary evaluation fails
    MANUAL_INPUT = "manual_input"                  # Direct user/client input


class OutputProvenance(BaseModel):
    """Explicit provenance metadata tracking how a domain output was produced."""

    model_config = ConfigDict(frozen=True)

    origin: ProvenanceOrigin = Field(description="Origin classification of the output")
    component: str = Field(description="Producing component or operation name, e.g. 'entity_resolver'")
    model_name: Optional[str] = Field(default=None, description="Model identifier if generated by model")
    provider: Optional[str] = Field(default=None, description="Provider identifier if generated by model")
    model_execution_id: Optional[str] = Field(default=None, description="FK to model_executions table if generated by model")
    rule_id: Optional[str] = Field(default=None, description="Rule or heuristic identifier if deterministic or fallback")
    is_fallback: bool = Field(default=False, description="Whether the output was produced via a fallback path")
